    "NOM_first_purchase = \"\"\"WITH first_purchase AS (SELECT customer_id, DATE(MIN(invoice_date), 'start of month') AS cohort_month  \n",
    "                        FROM customer_sales GROUP BY customer_id),\n",
    "customer_activity AS (SELECT DISTINCT customer_id, DATE(invoice_date, 'start of month') AS purchase_month FROM customer_sales)\n",
    "SELECT f.cohort_month, a.purchase_month, COUNT(DISTINCT a.customer_id) AS active_customers,\n",
    "((CAST(STRFTIME('%Y', a.purchase_month) AS INTEGER) - CAST(STRFTIME('%Y', f.cohort_month) AS INTEGER)) * 12\n",
    "+ (CAST(STRFTIME('%m', a.purchase_month) AS INTEGER) - CAST(STRFTIME('%m', f.cohort_month) AS INTEGER)) + 1) AS cohort_index\n",
    "FROM first_purchase f \n",
    "JOIN customer_activity a ON f.customer_id = a.customer_id\n",
